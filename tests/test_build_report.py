"""The report builder: placeholders, formats and the guard against literal numbers (Phase 10)."""

import json
import re
from pathlib import Path

import pytest

from scripts import build_report as br

REPO = Path(__file__).resolve().parent.parent
NUMBERS = {
    "meta.status": "FULL",
    "a.acc": 0.9364,
    "a.diff": -0.026,
    "a.gain": 0.121,
    "a.count": 11173962,
    "a.label": "beyond seed noise",
    "a.flag": True,
    "a.missing": None,
}


@pytest.mark.parametrize(
    ("key", "fmt", "expected"),
    [
        ("a.acc", "pct1", "93.6%"),
        ("a.gain", "pp1", "12.1 pp"),
        ("a.diff", "pp1", "-2.6 pp"),
        ("a.diff", "negpp1", "2.6 pp"),
        ("a.acc", "f3", "0.936"),
        ("a.acc", "f1", "0.9"),
        ("a.count", "int", "11,173,962"),
        ("a.label", None, "beyond seed noise"),
        ("a.flag", None, "yes"),
    ],
)
def test_formats(key, fmt, expected):
    assert br.format_value(key, NUMBERS[key], fmt) == expected


@pytest.mark.parametrize(
    ("key", "fmt", "message"),
    [
        ("a.gain", "negpp1", "positive"),  # words would say "lower" for a rise
        ("a.missing", "pct1", "null"),
        ("a.acc", None, "give a format"),
        ("a.label", "pct1", "needs a number"),
        ("a.acc", "int", "not an integer"),
        ("a.acc", "pct2", "unknown format"),
    ],
)
def test_bad_values_and_formats_fail(key, fmt, message):
    with pytest.raises(ValueError, match=message):
        br.format_value(key, NUMBERS[key], fmt)


def test_render_fills_placeholders():
    text = "ResNet-18 reaches {{a.acc|pct1}} on CIFAR-10-C ({{ a.label }})."
    assert (
        br.render(text, NUMBERS, "t").text
        == "ResNet-18 reaches 93.6% on CIFAR-10-C (beyond seed noise)."
    )


@pytest.mark.parametrize(
    "text",
    [
        "It reaches an accuracy of 91.2% on fog.",
        "The drop is 12 points.",
        "ResNet-18 loses 5 pp.",
        "| 0.84 | 0.93 |",
    ],
)
def test_literal_numbers_outside_placeholders_fail(text):
    with pytest.raises(ValueError, match="digits outside placeholders"):
        br.render(text, NUMBERS, "t")


def test_unknown_key_and_malformed_placeholder_fail():
    with pytest.raises(ValueError, match="unknown report number key"):
        br.render("{{no.such.key|pct1}}", NUMBERS, "t")
    with pytest.raises(ValueError, match="malformed placeholder"):
        br.render("{{a.label}", NUMBERS, "t")


def test_allow_list_hits_are_reported():
    hits = br.check_digits("Trained for 40 epochs with batch size 128 on CIFAR-10.", "t")
    assert hits == {
        "dataset": ["CIFAR-10"],
        "epochs": ["40 epochs"],
        "optimiser": ["batch size 128"],
    }


def test_allow_list_is_bound_to_its_context():
    for text in ("We use 40 for the run.", "Batch 128.", "Accuracy 100% on clean."):
        with pytest.raises(ValueError, match="digits outside placeholders"):
            br.check_digits(text, "t")


def _templates(tmp_path, good, second):
    pairs = []
    for name, text in (("one", good), ("two", second)):
        template = tmp_path / f"{name}.template.md"
        template.write_text(text)
        pairs.append((template, tmp_path / f"{name}.md"))
    return pairs


def test_partial_numbers_are_refused(tmp_path):
    path = tmp_path / "numbers.json"
    path.write_text(json.dumps({**NUMBERS, "meta.status": "PARTIAL"}))
    with pytest.raises(ValueError, match="not FULL"):
        br.build(path, _templates(tmp_path, "x", "y"))


def test_nothing_is_written_unless_every_template_succeeds(tmp_path):
    path = tmp_path / "numbers.json"
    path.write_text(json.dumps(NUMBERS))
    pairs = _templates(tmp_path, "{{a.acc|pct1}}", "accuracy of 91.2%")
    with pytest.raises(ValueError):
        br.build(path, pairs)
    assert not any(output.exists() for _, output in pairs)
    pairs = _templates(tmp_path, "{{a.acc|pct1}}", "{{a.label}}")
    br.build(path, pairs)
    assert pairs[0][1].read_text().endswith("93.6%")
    assert pairs[0][1].read_text().startswith("<!-- Generated by")


def test_committed_outputs_match_a_rebuild(tmp_path):
    pairs = [(t, tmp_path / o.name) for t, o in br.TEMPLATES]
    numbers = REPO / "results" / "tables" / "report_numbers.json"
    results = br.build(numbers, pairs)
    for (_, committed), (_, rebuilt) in zip(br.TEMPLATES, pairs, strict=True):
        assert rebuilt.read_text() == committed.read_text(), committed.name
    assert all(result.hits for result in results.values())


def test_report_cites_all_eight_figures():
    template = (REPO / "report" / "report.template.md").read_text()
    for n in range(1, 9):
        assert re.search(rf"\]\(\.\./results/figures/fig{n}_[a-z_]+\.png\)", template)
        assert f"Figure {n}" in template
        assert next((REPO / "results" / "figures").glob(f"fig{n}_*.png"), None) is not None


def test_only_citation_lines_are_exempt_in_the_references():
    entry = "1. Krizhevsky, A. (2009). *Tiny Images*. Report. https://example.org/a-2009-TR.pdf"
    assert "reference entry" in br.check_digits(f"## References\n\n{entry}\n", "t")
    with pytest.raises(ValueError, match="digits outside placeholders"):
        br.check_digits(f"## References\n\n{entry}\nThe model has an accuracy of 91.2%.\n", "t")
