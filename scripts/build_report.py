"""Fill the report and README templates from report_numbers.json (python -m scripts.build_report).

Renders `report/report.template.md` -> `report/report.md` and `README.template.md` -> `README.md`.
Every result number in those files must come from `$RESULTS_DIR/tables/report_numbers.json`
through a placeholder:

    {{main.resnet18.augmix.clean_acc.mean|pct1}}

Formats:
- `pct1`: fraction -> `93.4%`
- `pp1`: fraction difference -> `12.3 pp` (a negative value keeps its sign: `-2.6 pp`)
- `negpp1`: the negated difference, for prose that states the direction in words ("lower by").
  Fails if the value is positive, so the words cannot contradict the number.
- `f1`, `f3`: plain number with 1 or 3 decimals
- `int`: integer with thousands separators
- no format: the value as text; only for text and yes/no values, never for numbers

The build fails on an unknown key, an unknown format, a missing or null value, PARTIAL data, and
any digit in a template outside a placeholder that no `ALLOW_LIST` entry covers. The allow-list
holds only numbers that are not results (years, sizes, hyperparameters, section numbers, names);
every hit is printed so a reviewer can check it. In the README, fenced code blocks are not
exempt either: commands are matched by the same allow-list.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from src.utils import env_path

REPO = Path(__file__).resolve().parent.parent
TEMPLATES: tuple[tuple[Path, Path], ...] = (
    (REPO / "report" / "report.template.md", REPO / "report" / "report.md"),
    (REPO / "README.template.md", REPO / "README.md"),
)
PLACEHOLDER = re.compile(r"\{\{\s*([A-Za-z0-9_.\-]+)\s*(?:\|\s*([a-z0-9]+)\s*)?\}\}")
GENERATED_NOTE = (
    "<!-- Generated by `python -m scripts.build_report` from {template}. "
    "Edit the template, not this file. -->\n\n"
)

# (name, pattern, why it is not a result). Patterns are tried in this order on the template text
# with placeholders removed; each match is blanked out before the next pattern runs.
