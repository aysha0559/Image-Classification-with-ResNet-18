@dataclass
class Rendered:
    """A filled template and the allow-list hits found in it."""

    text: str
    hits: dict[str, list[str]]


def format_value(key: str, value: Any, fmt: str | None) -> str:
    """Return one placeholder's text; raise ValueError on a bad value or format."""
    if value is None:
        raise ValueError(f"{key} is null in report_numbers.json")
    if fmt is None:
        if isinstance(value, bool):
            return "yes" if value else "no"
        if isinstance(value, str):
            return value
        raise ValueError(f"{key} is a number; give a format (pct1, pp1, negpp1, f1, f3, int)")
    if isinstance(value, bool) or not isinstance(value, int | float):
        raise ValueError(f"{key} is {value!r}; format {fmt} needs a number")
    if fmt == "pct1":
        return f"{100 * value:.1f}%"
    if fmt == "pp1":
        return f"{100 * value:.1f} pp"
    if fmt == "negpp1":
        if value > 0:
            raise ValueError(f"{key} is {value}, positive; negpp1 is for negative differences")
        return f"{-100 * value:.1f} pp"
    if fmt == "f1":
        return f"{value:.1f}"
    if fmt == "f3":
        return f"{value:.3f}"
    if fmt == "int":
        if float(value) != int(value):
            raise ValueError(f"{key} is {value}, not an integer")
        return f"{int(value):,}"
    raise ValueError(f"unknown format {fmt!r} in {{{{{key}|{fmt}}}}}")


def check_digits(template: str, name: str) -> dict[str, list[str]]:
    """Return allow-list hits; raise ValueError listing every digit no entry covers."""
    text = PLACEHOLDER.sub("", template)
    hits: dict[str, list[str]] = defaultdict(list)
    for label, pattern, _ in ALLOW_LIST:
        regex = re.compile(pattern)
        hits[label] += [m.group(0) for m in regex.finditer(text)]
        text = regex.sub(lambda m: " " * len(m.group(0)), text)
    problems = [
        f"{name}:{number}: {line.strip()!r}"
        for number, line in enumerate(text.splitlines(), start=1)
        if re.search(r"\d", line)
    ]
    if problems:
        raise ValueError(
            "digits outside placeholders and the allow-list (put result numbers in "
            "placeholders):\n  " + "\n  ".join(problems)
        )
    return {label: found for label, found in hits.items() if found}


def render(template: str, numbers: dict[str, Any], name: str) -> Rendered:
    """Return the filled template; raise ValueError on any unknown key or stray digit."""
    hits = check_digits(template, name)
    unknown = sorted({m.group(1) for m in PLACEHOLDER.finditer(template)} - set(numbers))
    if unknown:
        raise ValueError(f"{name}: unknown report number key(s): {', '.join(unknown)}")
    leftover = re.findall(r"\{\{|\}\}", PLACEHOLDER.sub("", template))
    if leftover:
        raise ValueError(f"{name}: malformed placeholder (stray '{{{{' or '}}}}')")

    def fill(match: re.Match[str]) -> str:
        return format_value(match.group(1), numbers[match.group(1)], match.group(2))

    return Rendered(PLACEHOLDER.sub(fill, template), hits)


def load_numbers(path: Path) -> dict[str, Any]:
    """Return report_numbers.json; refuse PARTIAL data."""
    numbers = json.loads(path.read_text(encoding="utf-8"))
    if numbers.get("meta.status") != "FULL":
        raise ValueError(f"{path}: meta.status is {numbers.get('meta.status')!r}, not FULL")
    return numbers


def build(numbers_path: Path, templates=TEMPLATES) -> dict[Path, Rendered]:
    """Render every template; write nothing unless all succeed. Return output path -> result."""
    numbers = load_numbers(numbers_path)
    results = {}
    for template, output in templates:
        name = template.relative_to(REPO) if template.is_relative_to(REPO) else template
        results[output] = render(template.read_text(encoding="utf-8"), numbers, str(name))
        results[output].text = GENERATED_NOTE.format(template=name) + results[output].text
    for output, result in results.items():
        output.write_text(result.text, encoding="utf-8")
    return results


def print_hits(results: dict[Path, Rendered]) -> None:
    """Print every allow-list hit per output, with the reason of its entry."""
    reasons = {label: why for label, _, why in ALLOW_LIST}
    for output, result in results.items():
        print(f"{output.relative_to(REPO)}: allow-list hits (non-result numbers)")
        for label, found in result.hits.items():
            counts = defaultdict(int)
            for item in found:
                counts[" ".join(item.split())] += 1
            shown = ", ".join(f"{k!r} x{n}" if n > 1 else repr(k) for k, n in counts.items())
            print(f"  {label} [{reasons[label]}]: {shown}")


def main() -> None:
    """Command-line entry point (CONTRACTS C5)."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--quiet", action="store_true", help="do not print the allow-list hits")
    args = parser.parse_args()
    numbers_path = env_path("RESULTS_DIR") / "tables" / "report_numbers.json"
    try:
        results = build(numbers_path)
    except ValueError as error:
        print(f"ERROR: {error}", file=sys.stderr)
        raise SystemExit(1) from error
    if not args.quiet:
        print_hits(results)
    for output in results:
        print(f"wrote {output.relative_to(REPO)}")


if __name__ == "__main__":
    main()
